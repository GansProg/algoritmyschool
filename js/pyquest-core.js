  function pick(x, lang) {
    if (x && typeof x === 'object' && !Array.isArray(x)) return x[lang] != null ? x[lang] : x.ru;
    return x;
  }

  function codeLines(code) {
    return code.split('\n').filter(function (l) { return l.trim() && l.trim()[0] !== '#'; }).length;
  }

  // Разбор ошибки Python: { line, key, x, extra } — текст подставляет интерфейс
  function explain(err, offset, userLines) {
    var name = err && err.tp$name;
    var raw = String(err && err.toString ? err.toString() : err);
    var ln = null;
    if (err && err.traceback && err.traceback.length) ln = err.traceback[0].lineno - offset;
    var inUser = ln != null && ln >= 1 && ln <= userLines;
    var line = inUser ? ln : null;
    var m;
    if (name === 'NameError' && (m = /name '([^']+)'/.exec(raw))) return { line: line, key: 'q.e.name', x: m[1] };
    if (name === 'IndentationError') return { line: line, key: 'q.e.indent' };
    if (name === 'SyntaxError' || name === 'ParseError' || name === 'TokenError') {
      return inUser ? { line: line, key: 'q.e.syntax' } : { line: null, key: 'q.e.syntaxEnd' };
    }
    if (name === 'TimeoutError' || /TimeLimitError|time limit/i.test(raw)) return { line: null, key: 'q.e.timeout' };
    if (name === 'TypeError') return { line: line, key: 'q.e.type', extra: raw.replace(/ on line \d+/, '') };
    if (name === 'ZeroDivisionError') return { line: line, key: 'q.e.zero' };
    return { line: line, key: null, extra: raw.replace(/ on line \d+/, '') };
  }

  // Выполняет один прогон главы. Возвращает Promise со списком событий.
  function runOnce(Sk, chapter, params, userCode, lang) {
    var head = '_T = ' + JSON.stringify(pick(chapter.T, lang)) + '\n' +
      '_TIRED = ' + JSON.stringify(TIRED[lang] || TIRED.ru) + '\n' +
      COMMON + chapter.world(params) + '\n';
    var offset = head.split('\n').length - 1;
    var source = head + userCode + '\n' + chapter.check + '\n';
    var events = [];
    var buf = '';
    function flush(line) {
      if (line.indexOf('@@EV\t') === 0) {
        var p = line.split('\t');
        if (p[1] === 'act') events.push({ kind: 'act', code: p[2], text: p[3] });
        else events.push({ kind: p[1], text: p[2] });
      } else {
        events.push({ kind: 'print', code: line });
      }
    }
    Sk.configure({
      output: function (t) {
        buf += t;
        var i;
        while ((i = buf.indexOf('\n')) >= 0) { flush(buf.slice(0, i)); buf = buf.slice(i + 1); }
      },
      read: function (f) {
        var files = Sk.builtinFiles && Sk.builtinFiles.files;
        if (!files || files[f] === undefined) throw new Error('File not found: ' + f);
        return files[f];
      },
      __future__: Sk.python3,
      execLimit: 4000,
      yieldLimit: 100
    });
    return Sk.misceval.asyncToPromise(function () {
      return Sk.importMainWithBody('<quest>', false, source, true);
    }).then(function () {
      if (buf) flush(buf);
      return { events: events };
    }, function (err) {
      if (buf) flush(buf);
      if (err && err.tp$name === '_Fail') return { events: events };
      var ex = explain(err, offset, userCode.split('\n').length);
      events.push({ kind: 'error', err: ex });
      return { events: events, error: ex };
    });
  }

  function runAll(Sk, chapter, userCode, lang) {
    lang = lang || 'kk';
    var results = [];
    var chain = Promise.resolve();
    chapter.runs.forEach(function (p) {
      chain = chain.then(function () {
        return runOnce(Sk, chapter, p, userCode, lang).then(function (r) {
          r.label = pick(p.label, lang);
          r.ok = r.events.some(function (e) { return e.kind === 'win'; });
          results.push(r);
        });
      });
    });
    return chain.then(function () {
      var lines = codeLines(userCode);
      var tooLong = chapter.maxLines && lines > chapter.maxLines;
      return { runs: results, lines: lines, tooLong: tooLong, ok: !tooLong && results.every(function (r) { return r.ok; }) };
    });
  }

